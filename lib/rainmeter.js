const fs = require("fs");
const path = require("path");
const os = require("os");
const { spawn } = require("child_process");

const CONFIG_NAME = "Bockis-eDEX";

function existingFile(candidates) {
  return candidates.find((candidate) => candidate && fs.existsSync(candidate)) || null;
}

function rainmeterExecutable() {
  const programFiles = process.env.ProgramFiles || "C:\\Program Files";
  const programFilesX86 = process.env["ProgramFiles(x86)"] || "C:\\Program Files (x86)";
  return existingFile([
    process.env.RAINMETER_EXE,
    path.join(programFiles, "Rainmeter", "Rainmeter.exe"),
    path.join(programFilesX86, "Rainmeter", "Rainmeter.exe"),
    path.join(process.env.LOCALAPPDATA || "", "Rainmeter", "Rainmeter.exe")
  ]);
}

function skinDirectory() {
  return path.join(os.homedir(), "Documents", "Rainmeter", "Skins", CONFIG_NAME);
}

function normalizeHex(value, fallback) {
  const text = String(value || "").trim();
  return /^#[0-9a-f]{6}$/i.test(text) ? text.toUpperCase() : fallback;
}

function themeColors(theme) {
  const colors = theme?.colors || {};
  const foreground = normalizeHex(theme?.terminal?.foreground, "#00EAFF");
  const background = normalizeHex(theme?.terminal?.background, "#01080B");
  const accent = Number.isFinite(Number(colors.r)) && Number.isFinite(Number(colors.g)) && Number.isFinite(Number(colors.b))
    ? `#${[colors.r, colors.g, colors.b].map((value) => Math.max(0, Math.min(255, Math.round(Number(value)))).toString(16).padStart(2, "0")).join("")}`.toUpperCase()
    : foreground;
  return { foreground, background, accent };
}

function skinIni(theme) {
  const colors = themeColors(theme);
  return `; Generated by Bockis-eDEX Desktop UI. Do not edit while the app is running.\n[Rainmeter]\nUpdate=1000\nAccurateText=1\nDynamicWindowSize=1\nBackgroundMode=2\nSolidColor=${colors.background.replace("#", "")},E6\n\n[Variables]\nAccent=${colors.accent.replace("#", "") }\nForeground=${colors.foreground.replace("#", "") }\nFontFace=Consolas\n\n[MeasureTime]\nMeasure=Time\nFormat=%H:%M:%S\n\n[MeasureDate]\nMeasure=Time\nFormat=%Y-%m-%d\n\n[MeasureCPU]\nMeasure=CPU\nProcessor=0\n\n[MeasureRAM]\nMeasure=PhysicalMemory\n\n[MeterTitle]\nMeter=String\nText=Bockis-eDEX\nFontFace=#FontFace#\nFontSize=12\nFontColor=#Accent#\nAntiAlias=1\nX=18\nY=14\n\n[MeterTime]\nMeter=String\nMeasureName=MeasureTime\nText=%1\nFontFace=#FontFace#\nFontSize=28\nFontColor=#Foreground#\nAntiAlias=1\nX=18\nY=34\n\n[MeterDate]\nMeter=String\nMeasureName=MeasureDate\nText=%1\nFontFace=#FontFace#\nFontSize=10\nFontColor=#Foreground#\nAntiAlias=1\nX=20\nY=76\n\n[MeterCPU]\nMeter=String\nMeasureName=MeasureCPU\nText=CPU  %1%\nFontFace=#FontFace#\nFontSize=10\nFontColor=#Foreground#\nAntiAlias=1\nX=20\nY=98\n\n[MeterRAM]\nMeter=String\nMeasureName=MeasureRAM\nText=RAM  %1%\nFontFace=#FontFace#\nFontSize=10\nFontColor=#Foreground#\nAntiAlias=1\nX=20\nY=116\n`;
}

function runRainmeter(executable, args) {
  return new Promise((resolve) => {
    if (!executable) {
      resolve(false);
      return;
    }
    const child = spawn(executable, args, { windowsHide: true, stdio: "ignore" });
    child.once("error", () => resolve(false));
    child.once("close", (code) => resolve(code === 0));
  });
}

async function syncRainmeter(theme, enabled) {
  const directory = skinDirectory();
  if (!enabled) {
    await stopRainmeter();
    return { enabled: false, installed: Boolean(rainmeterExecutable()), directory };
  }
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, `${CONFIG_NAME}.ini`), skinIni(theme), "utf8");
  const executable = rainmeterExecutable();
  if (!executable) return { enabled: true, installed: false, directory };
  await runRainmeter(executable, ["!Refresh", CONFIG_NAME]);
  await runRainmeter(executable, ["!ActivateConfig", CONFIG_NAME, `${CONFIG_NAME}.ini`]);
  return { enabled: true, installed: true, directory };
}

async function stopRainmeter() {
  const executable = rainmeterExecutable();
  if (executable) await runRainmeter(executable, ["!DeactivateConfig", CONFIG_NAME]);
}

function status() {
  return {
    installed: Boolean(rainmeterExecutable()),
    directory: skinDirectory(),
    config: CONFIG_NAME
  };
}

module.exports = { syncRainmeter, stopRainmeter, status, skinDirectory };
